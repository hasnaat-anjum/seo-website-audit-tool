"""Turn audit results into Markdown, JSON or a styled single-file HTML report."""

from __future__ import annotations

import html
import json
from datetime import datetime

from .analyzer import PageData
from .checks import Check


def to_json(page: PageData, checks: list[Check], score: int, grade: str) -> str:
    """Machine-readable report, useful for CI pipelines."""
    report = {
        "url": page.url,
        "audited_at": datetime.now().isoformat(timespec="seconds"),
        "score": score,
        "grade": grade,
        "summary": {
            "title": page.title,
            "word_count": page.word_count,
            "headings": len(page.headings),
            "images": len(page.images),
            "images_missing_alt": page.images_missing_alt,
            "links": len(page.links),
            "internal_links": page.internal_links,
            "external_links": page.external_links,
        },
        "checks": [
            {
                "name": c.name,
                "status": c.status,
                "message": c.message,
                "points": f"{c.points}/{c.weight}",
            }
            for c in checks
        ],
    }
    return json.dumps(report, indent=2)


def to_markdown(page: PageData, checks: list[Check], score: int, grade: str) -> str:
    """Human-readable report for pasting into a doc or a GitHub issue."""
    passed = sum(1 for c in checks if c.status == "pass")
    lines = [
        f"# SEO Audit Report — {page.url or 'local file'}",
        "",
        f"**Score: {score}/100 (Grade {grade})** — "
        f"{passed}/{len(checks)} checks passed.",
        "",
        "## Summary",
        "",
        f"- Title: {page.title or '(missing)'}",
        f"- Words: {page.word_count}",
        f"- Headings: {len(page.headings)} (H1: {page.h1_count})",
        f"- Images: {len(page.images)} "
        f"({page.images_missing_alt} missing alt text)",
        f"- Links: {len(page.links)} "
        f"({page.internal_links} internal, {page.external_links} external)",
        "",
        "## Checks",
        "",
    ]
    icon = {"pass": "✅", "warning": "⚠️", "fail": "❌"}
    for c in checks:
        lines.append(f"- {icon[c.status]} **{c.name}** ({c.points}/{c.weight}) — {c.message}")
    lines.append("")
    lines.append("_Generated by SEO Website Audit Tool._")
    return "\n".join(lines)


def to_html(page: PageData, checks: list[Check], score: int, grade: str) -> str:
    """A clean, shareable single-file HTML report (no external assets)."""
    passed = sum(1 for c in checks if c.status == "pass")
    colour = {"A": "#16a34a", "B": "#65a30d", "C": "#ca8a04",
              "D": "#ea580c", "F": "#dc2626"}[grade]
    badge = {"pass": ("✅ Pass", "#dcfce7", "#166534"),
             "warning": ("⚠️ Warning", "#fef9c3", "#854d0e"),
             "fail": ("❌ Fail", "#fee2e2", "#991b1b")}
    rows = ""
    for c in checks:
        label, bg, fg = badge[c.status]
        rows += (
            f'<tr><td><strong>{html.escape(c.name)}</strong></td>'
            f'<td><span style="background:{bg};color:{fg};padding:2px 8px;'
            f'border-radius:999px;font-size:13px">{label}</span></td>'
            f'<td>{html.escape(c.message)}</td>'
            f'<td style="text-align:right">{c.points}/{c.weight}</td></tr>\n'
        )
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>SEO Audit Report — {html.escape(page.url or 'local file')}</title>
<style>
  body {{ font-family: system-ui, sans-serif; max-width: 900px; margin: 40px auto;
         padding: 0 20px; color: #1f2937; }}
  .score {{ font-size: 64px; font-weight: 800; color: {colour}; line-height: 1; }}
  table {{ width: 100%; border-collapse: collapse; margin-top: 24px; }}
  th, td {{ text-align: left; padding: 10px 8px; border-bottom: 1px solid #e5e7eb;
            vertical-align: top; }}
  th {{ background: #f9fafb; }}
</style>
</head>
<body>
  <h1>SEO Audit Report</h1>
  <p><strong>{html.escape(page.url or 'local file')}</strong><br>
  Audited {datetime.now().strftime('%Y-%m-%d %H:%M')}</p>
  <div class="score">{score}<span style="font-size:28px">/100</span></div>
  <p style="font-size:20px">Grade {grade} — {passed}/{len(checks)} checks passed</p>
  <p>Title: {html.escape(page.title) or '(missing)'} · Words: {page.word_count} ·
  Images: {len(page.images)} ({page.images_missing_alt} missing alt) ·
  Links: {len(page.links)} ({page.internal_links} internal,
  {page.external_links} external)</p>
  <table>
    <tr><th>Check</th><th>Status</th><th>What it means</th><th>Points</th></tr>
    {rows}
  </table>
  <p style="color:#6b7280;font-size:13px">Generated by SEO Website Audit Tool.</p>
</body>
</html>
"""
